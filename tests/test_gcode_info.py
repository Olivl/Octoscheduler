import base64
import os
import struct
import sys
import tempfile
import unittest
import zlib

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "octoprint_octoscheduler"))
import gcode_info  # noqa: E402


def png_1x1():
    return gcode_info._png_encode_rgba(1, 1, b"\xff\x00\x00\xff")


def qoi_2x1():
    # 2 pixels : un QOI_OP_RGBA rouge puis un RUN de 1
    body = b"\xff" + bytes((255, 0, 0, 255)) + bytes((0xC0 | 0,))
    return b"qoif" + struct.pack(">IIBB", 2, 1, 4, 0) + body + b"\x00" * 7 + b"\x01"


def thumb_block(tag, w, h, raw):
    b64 = base64.b64encode(raw).decode()
    lines = ["; {} begin {}x{} {}".format(tag, w, h, len(b64))]
    lines += ["; " + b64[i : i + 78] for i in range(0, len(b64), 78)]
    lines.append("; {} end".format(tag))
    return "\n".join(lines)


class TestDuration(unittest.TestCase):
    def test_formats(self):
        self.assertEqual(gcode_info.parse_duration("1d 2h 3m 4s"), 93784)
        self.assertEqual(gcode_info.parse_duration("2h 5m"), 7500)
        self.assertEqual(gcode_info.parse_duration("1 hours 23 minutes"), 4980)
        self.assertIsNone(gcode_info.parse_duration("n/a"))


class TestExtract(unittest.TestCase):
    def _write(self, text):
        fd, path = tempfile.mkstemp(suffix=".gcode")
        with os.fdopen(fd, "w") as f:
            f.write(text)
        self.addCleanup(os.remove, path)
        return path

    def test_prusaslicer(self):
        text = "\n".join(
            [
                "; generated by PrusaSlicer",
                thumb_block("thumbnail", 16, 16, b"small"),
                thumb_block("thumbnail", 1, 1, png_1x1()),
                "G28",
                "G1 X10 Y10",
            ]
            + ["G1 X1"] * 50000
            + ["; estimated printing time (normal mode) = 1h 2m 3s"]
        )
        info = gcode_info.extract_info(self._write(text))
        self.assertEqual(info["estimated_time"], 3723)
        mime, raw = info["thumbnail"]
        self.assertEqual(mime, "image/png")
        self.assertTrue(raw.startswith(b"\x89PNG"))

    def test_cura(self):
        info = gcode_info.extract_info(self._write(";FLAVOR:Marlin\n;TIME:5400\nG28\n"))
        self.assertEqual(info["estimated_time"], 5400)
        self.assertIsNone(info["thumbnail"])

    def test_orca_header(self):
        text = "; HEADER_BLOCK_START\n; model printing time: 1h 30m; total estimated time: 1h 35m\nG28\n"
        self.assertEqual(gcode_info.extract_info(self._write(text))["estimated_time"], 5400)

    def test_qoi(self):
        text = thumb_block("thumbnail_QOI", 2, 1, qoi_2x1()) + "\nG28\n"
        mime, raw = gcode_info.extract_info(self._write(text))["thumbnail"]
        self.assertEqual(mime, "image/png")
        # vérifier les pixels décodés
        w, h, px = gcode_info._qoi_decode(qoi_2x1())
        self.assertEqual((w, h), (2, 1))
        self.assertEqual(px, bytes((255, 0, 0, 255)) * 2)
        idat = raw[raw.index(b"IDAT") + 4 : raw.index(b"IEND") - 8]
        self.assertEqual(zlib.decompress(idat), b"\x00" + px)


if __name__ == "__main__":
    unittest.main()
